// Regenerates sample-data.js from the real sample repo files and the cached
// outputs, so the app works from file:// with no network. Run:
//   node scripts/build-sample-data.js
const fs = require("node:fs");
const path = require("node:path");
const core = require("../core");

const root = path.join(__dirname, "..");
const repoRoot = path.join(root, "sample-repo", "campus-queue");
const files = [];
(function walk(dir, rel) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    const r = rel ? rel + "/" + entry.name : entry.name;
    if (entry.isDirectory()) walk(p, r);
    else files.push({ path: r, content: fs.readFileSync(p, "utf8") });
  }
})(repoRoot, "");

const facts = core.analyseRepo(files, "sivasai/campus-queue");
const readme = core.buildReadme(facts);
const script = core.buildScript(facts);
const deck = core.buildDeck(facts);

const data = { repo: "sivasai/campus-queue", files, facts, readme: readme.markdown, readmeSections: readme.sections, script, deck };
fs.writeFileSync(
  path.join(root, "sample-data.js"),
  "// Generated by scripts/build-sample-data.js — do not edit by hand.\n" +
    "// Contents are the real files of sample-repo/campus-queue plus the\n" +
    "// artefacts core.js builds from them.\n" +
    "window.SAMPLE_DATA = " + JSON.stringify(data, null, 2) + ";\n"
);
console.log("sample-data.js written:", files.length, "files, grounding problems:", core.checkGrounding(facts, deck).length);
